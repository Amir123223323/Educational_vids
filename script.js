 function createlink(){
    const course_select = document.getElementById('teacher');
    let teacher = course_select.options[course_select.selectedIndex].textContent;
    let test = document.getElementById("help");
    let path = teachers[teacher][0];
    const number = document.querySelector("#number");
    const link = document.querySelector("#link");
    number.placeholder = `1-${path.length}`;
    let num = Number(number.value);
    if (0 < num && num<= path.length && num - Math.floor(num) === 0)
        {
            link.href = path[num - 1];
            link.textContent = `${teachers[teacher][1]} جلسه ${num} ام`;
        }
        else{
            test.textContent = `لطفا عدد صحیح از 1 تا ${path.length} را انتخاب کنید`;
            test.style.color = "#b4ffff";
            link.textContent = null;
            link.href = null;
        }                 
}
